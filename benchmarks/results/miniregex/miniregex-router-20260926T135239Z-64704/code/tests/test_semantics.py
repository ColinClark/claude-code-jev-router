"""Hand-picked patterns compared against re on a set of texts."""

import pytest
from helpers import assert_same

TEXTS = [
    "",
    "a",
    "ab",
    "abc",
    "aaa",
    "abab",
    "aab\n",
    "a\nb",
    "\n",
    "xyz",
    "a1 b2_c3",
    "  tab\there ",
    "[x]-{y}",
    "a.b*c+d?e",
    "foo@bar.com",
    "ccbbaa",
]

PATTERNS = [
    # literals and escapes
    "a",
    "abc",
    r"a\.b",
    r"\\",
    r"\*\+\?",
    r"\(\)\[\]\{\}",
    r"\|\^\$\-",
    r"\.",
    r"\n",
    r"a\tb|\t",
    # dot and classes
    ".",
    "a.c",
    ".*",
    r"\d",
    r"\D+",
    r"\w+",
    r"\W",
    r"\s+",
    r"\S+",
    r"\w+@\w+\.\w+",
    # sets
    "[abc]",
    "[a-c]+",
    "[^a-c]+",
    "[^\n]",
    r"[\d]",
    r"[\w.]+",
    r"[^\s]+",
    r"[\D]",
    r"[\S\s]",
    r"[\W]",
    "[-a]",
    "[a-]",
    "[]a]",
    "[^]a]",
    r"[\]\[]",
    r"[\-x]",
    r"[a\-z]",
    r"[\\]",
    "[.*+?]",
    "[$^]",
    "[a-cx-z]",
    "[--/]",
    "[{}]",
    # anchors
    "^a",
    "a$",
    "^$",
    "$",
    "^",
    r"b$|\n$",
    "^ab|ab$",
    "(^a|b$)*",
    "a$\n?",
    # quantifiers
    "a*",
    "a+",
    "a?",
    "a*?",
    "a+?",
    "a??",
    "a{2}",
    "a{2,}",
    "a{1,2}",
    "a{,2}",
    "a{0}",
    "a{,}",
    "a{2}?",
    "a{1,}?",
    "a{0,2}?",
    "a{,2}?",
    "(?:ab)*",
    "(?:ab)+?",
    "(?:ab){1,2}",
    "(?:a|b){2,3}?c?",
    ".*b",
    ".*?b",
    "a*a",
    "a*?a",
    "(a*)*",
    "(a*)+",
    "(a*?)*",
    "(a|)*",
    "(|a)*",
    "(|a)+?",
    "(a?)+?b",
    "(a?){2,}",
    "(a?){,3}?b",
    "((a)|b)*",
    # groups and alternation
    "(a)",
    "(a)(b)?",
    "(a)|(b)",
    "(a|ab)(c|bcd)?",
    "(a|b)*c",
    "(a|b)*?c",
    "((a)(b))*",
    "(?:(a)|(b))*",
    "(?:(a)|b)*",
    "(?:(a)b|a)(c)?",
    "(a)?(a)?a",
    "(?:a|())*",
    "(?:()|a)*",
    "()",
    "(?:)",
    "a||b",
    "|",
    "(|b)",
    "((((a))))",
    "(a(b(c)))",
    "(x)?y|(a)",
    "(\\w)(\\w)?",
    "([ab])+",
    "([ab])+?b",
    "(.)(.)(.)?",
    "(?:(\\d)|[a-z])+",
]


@pytest.mark.parametrize("pattern", PATTERNS)
def test_matches_re(pattern):
    for text in TEXTS:
        assert_same(pattern, text)
