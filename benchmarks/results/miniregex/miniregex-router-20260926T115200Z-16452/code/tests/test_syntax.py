@pytest.mark.parametrize("pattern", INVALID_PATTERNS)
def test_invalid_patterns_raise_regex_error(pattern: str) -> None:
    with pytest.raises(re.error):
        re.compile(pattern)
    with pytest.raises(RegexError):
        compile(pattern)


