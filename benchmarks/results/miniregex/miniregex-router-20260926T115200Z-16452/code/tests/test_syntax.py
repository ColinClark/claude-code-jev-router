@pytest.mark.parametrize("pattern", UNSUPPORTED_BUT_VALID_IN_RE)
def test_documented_unsupported_syntax_raises_regex_error(pattern: str) -> None:
    """Out-of-scope syntax is rejected with RegexError (never silently mis-parsed)."""
    with pytest.raises(RegexError):
        compile(pattern)


def test_huge_repeat_count_is_rejected() -> None:
    with pytest.raises(RegexError):
        compile("a{4294967295}")
    with pytest.raises(RegexError):
        compile("a{1,99999999999}")
    assert compile("a{4294967294}") is not None
