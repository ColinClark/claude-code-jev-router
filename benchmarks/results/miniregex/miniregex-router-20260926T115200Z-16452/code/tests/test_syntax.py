@pytest.mark.parametrize("pattern", FEATURES)
def test_feature_matches_re(pattern: str) -> None:
    re.compile(pattern)  # every entry in the table must be valid for re
    for text in TEXTS + TEXTS_FOR_BRACES:
        assert_same(pattern, text)


