def _cases() -> list[str]:
    return ARITHMETIC + CONCAT_AND_FORMAT + COMPARISON + LOGIC + IN_BETWEEN + LIKE + FUNCTIONS + (
        PRECEDENCE + LITERALS
    )


@pytest.mark.parametrize("expr", _cases())
def test_scalar_expression(empty_pair, expr: str) -> None:
    empty_pair.check(f"SELECT {expr}")


