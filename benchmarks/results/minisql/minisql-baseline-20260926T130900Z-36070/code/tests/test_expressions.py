@pytest.fixture
def dual_scalar(dual):
    # The supported grammar requires FROM table; use a one-row dummy table
    # to exercise scalar expressions the same way against both engines.
    dual.run("CREATE TABLE dummy (x INTEGER)")
    dual.run("INSERT INTO dummy VALUES (0)")
    return dual


@pytest.mark.parametrize("expr", EXPRESSIONS)
def test_expression_matches_sqlite(dual_scalar, expr):
    dual_scalar.query(f"SELECT {expr} FROM dummy", ordered=True)
