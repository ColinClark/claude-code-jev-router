@pytest.mark.parametrize(
    "expr",
    ARITHMETIC + COMPARISON + LOGIC + IN_BETWEEN + LIKE + CONCAT + LITERALS + FUNCTIONS,
)
def test_scalar_expression(pair, expr):
    pair.query(f"SELECT {expr}")


def test_multiple_columns_and_trailing_semicolon(pair):
    pair.query("SELECT 1, 'a', NULL, 2.5, 1 < 2;")


def test_booleans_are_ints(pair):
    rows = pair.query("SELECT 1 < 2, 1 = 2, NOT 0, 1 IN (1), 'a' LIKE 'A', 1 IS NULL")
    assert all(type(value) is int for value in rows[0])


def test_case_insensitive_keywords(pair):
    pair.query("sElEcT 1 aNd 0, 2 bEtWeEn 1 AnD 3, NuLl iS nUlL")


