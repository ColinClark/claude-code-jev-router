"""Summarize benchmark runs into benchmarks/results/<task>/RESULTS.md.

  python3 benchmarks/summarize.py tinykv

Cost and tokens come from Claude Code's own headless result (authoritative for the whole run, including
subagents). The per-lane split comes from router-report. Tests are the harness's independent re-run.
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def load(run_dir: Path) -> dict | None:
    try:
        meta = json.loads((run_dir / "meta.json").read_text())
        result = json.loads((run_dir / "result.json").read_text())
        checks = json.loads((run_dir / "checks.json").read_text())
    except (OSError, ValueError):
        return None
    try:
        report = json.loads((run_dir / "report.json").read_text())
    except (OSError, ValueError):
        report = {}
    try:
        acceptance = json.loads((run_dir / "acceptance.json").read_text())
    except (OSError, ValueError):
        acceptance = None
    decisions = []
    decisions_file = run_dir / "decisions.jsonl"
    for line in decisions_file.read_text().splitlines() if decisions_file.exists() else []:
        try:
            decisions.append(json.loads(line))
        except ValueError:
            continue
    usage = result.get("modelUsage") or {}
    return {
        "dir": run_dir.name,
        "meta": meta,
        "result": result,
        "checks": checks,
        "report": report,
        "decisions": decisions,
        "acceptance": acceptance,
        "cost": float(result.get("total_cost_usd") or 0),
        "seconds": meta.get("wall_seconds") or round((result.get("duration_ms") or 0) / 1000),
        "turns": result.get("num_turns"),
        "output_tokens": sum(int(u.get("outputTokens") or 0) for u in usage.values()),
        "cache_read": sum(int(u.get("cacheReadInputTokens") or 0) for u in usage.values()),
        "models": sorted(usage),
        "ok": not result.get("is_error") and checks["pytest"]["exit_code"] == 0 and checks["ruff"]["exit_code"] == 0,
    }


def bug_groups(run: dict) -> dict[str, bool] | None:
    """For suites with tests named test_bugN_*: bug id -> fixed (every test in the group passed)."""
    tests = (run["acceptance"] or {}).get("tests") or {}
    groups: dict[str, bool] = {}
    for name, outcome in tests.items():
        if name.startswith("test_bug"):
            bug = name.split("_")[1]
            groups[bug] = groups.get(bug, True) and outcome == "PASSED"
    return groups or None


def acceptance_cell(run: dict) -> str:
    a = run["acceptance"]
    if not a:
        return "not graded"
    cell = f"{a['passed']}/{a['total']}"
    groups = bug_groups(run)
    if groups:
        cell += f" · bugs fixed {sum(groups.values())}/{len(groups)}"
    return cell


def lanes_line(run: dict) -> str:
    agents = (run["report"] or {}).get("by_agent") or {}
    total = sum(a.get("est_cost_usd", 0) for a in agents.values()) or 1
    parts = []
    for name, a in sorted(agents.items(), key=lambda kv: -kv[1].get("est_cost_usd", 0)):
        lane = a.get("lane")
        label = name if lane in ("—", "not a router lane", None) else f"{lane} ({name})"
        parts.append(f"{label} {a.get('requests', 0)} req, {a.get('est_cost_usd', 0) / total:.0%} of cost")
    return "; ".join(parts) or "n/a"


def decisions_line(run: dict) -> str:
    classify = [d for d in run["decisions"] if d.get("tool") == "classify_task"]
    gate = [d for d in run["decisions"] if d.get("tool") == "dispatch_gate"]
    other = [d for d in run["decisions"] if d.get("tool") not in ("classify_task", "dispatch_gate")]
    if not classify and not gate and not other:
        return "none"
    units = ", ".join(
        f"`{d.get('task_id', '').split(':', 1)[-1]}` → {d.get('class')}/{(d.get('route') or {}).get('lane')} "
        f"({d.get('confidence')})"
        for d in classify
    )
    blocked = sum(1 for d in gate if d.get("action") == "BLOCKED_DISPATCH")
    allowed = sum(1 for d in gate if str(d.get("action", "")).startswith("ALLOWED"))
    extra = f"; other decisions: {len(other)}" if other else ""
    return f"{units or 'no classifications'}; gate allowed {allowed}, blocked {blocked}{extra}"


def fmt_minutes(seconds: float) -> str:
    return f"{seconds / 60:.1f} min"


def config(run: dict) -> str:
    """Configuration label: mode, main-session model and effort, and router policy version."""
    meta = run["meta"]
    model = meta["model"].removeprefix("claude-")
    label = f"{meta['mode']} · {model}/{meta['effort']}"
    return label + (f" · policy {meta['router_policy']}" if meta.get("router_policy") else "")


def render(task: str, runs: list[dict]) -> str:
    runs.sort(key=lambda r: (config(r), r["meta"]["started"]))
    out = [
        f"# Benchmark results: {task}",
        "",
        "_Generated by `benchmarks/summarize.py`. Do not edit by hand._",
        "",
        f"Prompt: [`benchmarks/{task}/prompt.md`](../../{task}/prompt.md). Every run starts from the same seed "
        "repo and budget. A configuration is the mode, the main-session (orchestrator) model and effort, and, for "
        "router runs, the router policy version, which sets the lane models. **baseline** sets "
        "`CLAUDE_ROUTER=off`; **router** uses the installed smart router. Cost is Claude Code's own "
        "`total_cost_usd` (API list prices). **Own tests** are the tests each run wrote, re-run independently by "
        "the harness; **hidden acceptance** is a fixed suite written from the prompt alone "
        "([`acceptance/`](../../" + task + "/acceptance/)) that neither mode sees.",
        "",
        "| Run | Configuration | Success | Hidden acceptance | Own tests | Wall time | Turns | Output tokens | Cost "
        "| Models |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in runs:
        c = r["checks"]
        out.append(
            f"| `{r['dir']}` | {config(r)} | {'✅' if r['ok'] else '❌'} | {acceptance_cell(r)} | "
            f"{c['pytest']['passed']} passed"
            f"{', ' + str(c['pytest']['failed']) + ' failed' if c['pytest']['failed'] else ''} | "
            f"{fmt_minutes(r['seconds'])} | {r['turns']} | {r['output_tokens']:,} | ${r['cost']:.2f} | "
            f"{', '.join(r['models'])} |"
        )

    out += [
        "",
        "## Averages by configuration",
        "",
        "| Configuration | Runs | Success | Hidden acceptance (all passed) | Mean cost | Mean wall time "
        "| Mean output tokens |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for mode in sorted({config(r) for r in runs}):
        group = [r for r in runs if config(r) == mode]
        graded = [r for r in group if r["acceptance"]]
        full = sum(1 for r in graded if r["acceptance"]["passed"] == r["acceptance"]["total"])
        out.append(
            f"| {mode} | {len(group)} | {sum(r['ok'] for r in group)}/{len(group)} | {full}/{len(graded)} | "
            f"${statistics.mean(r['cost'] for r in group):.2f} | "
            f"{fmt_minutes(statistics.mean(r['seconds'] for r in group))} | "
            f"{statistics.mean(r['output_tokens'] for r in group):,.0f} |"
        )

    out += ["", "## Where the work ran", ""]
    for r in runs:
        out += [
            f"**`{r['dir']}`** ({config(r)})",
            "",
            f"- Lanes and agents: {lanes_line(r)}",
            f"- Router decisions: {decisions_line(r)}",
            "",
        ]
    out += ["Generated code for each run is under `results/" + task + "/<run>/code/`."]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    task = argv[1] if len(argv) > 1 else "tinykv"
    base = ROOT / "results" / task
    runs = [r for d in sorted(base.iterdir()) if d.is_dir() and (r := load(d))] if base.exists() else []
    if not runs:
        print(f"no runs under {base}", file=sys.stderr)
        return 1
    (base / "RESULTS.md").write_text(render(task, runs))
    print(f"wrote {base / 'RESULTS.md'} ({len(runs)} runs)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
